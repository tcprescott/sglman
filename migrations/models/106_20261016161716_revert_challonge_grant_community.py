async def upgrade(db: BaseDBAsyncClient) -> str:
    # Undoes migration 105. A tenant left with both a community grant and a
    # no-community grant keeps the community one: the newest row becomes the
    # only connection again, and every linked bracket lives in a community.
    return """
        DELETE FROM "challongeconnection" AS c
        WHERE c."community" = ''
          AND EXISTS (
              SELECT 1 FROM "challongeconnection" AS o
              WHERE o."tenant_id" = c."tenant_id" AND o."community" <> ''
          );
        ALTER TABLE "challongeconnection" DROP COLUMN "community";"""


async def downgrade(db: BaseDBAsyncClient) -> str:
    return """
        ALTER TABLE "challongeconnection" ADD "community" VARCHAR(100);"""


